"use strict";
const electron = require("electron");
electron.contextBridge.exposeInMainWorld("electron", {
  getVRMPath: () => electron.ipcRenderer.invoke("get-vrm-path"),
  loadVRM: (filePath) => electron.ipcRenderer.invoke("load-vrm", filePath),
  getAnimations: () => electron.ipcRenderer.invoke("get-animations"),
  loadAnimation: (filePath) => electron.ipcRenderer.invoke("load-animation", filePath),
  dragStart: (x, y) => electron.ipcRenderer.send("drag-start", { x, y }),
  dragMove: (x, y) => electron.ipcRenderer.send("drag-move", { x, y }),
  dragEnd: () => electron.ipcRenderer.send("drag-end"),
  closeWindow: () => electron.ipcRenderer.send("window-close"),
  resizeWindow: (delta) => electron.ipcRenderer.send("resize-window", delta),
  setIgnoreMouse: (ignore) => electron.ipcRenderer.send("set-ignore-mouse", ignore),
  setWindowBounds: (w, h) => electron.ipcRenderer.send("set-window-bounds", { w, h }),
  getApiKey: () => electron.ipcRenderer.invoke("get-api-key"),
  setApiKey: (key) => electron.ipcRenderer.invoke("set-api-key", key),
  chat: (messages, visionImage = null) => electron.ipcRenderer.invoke("chat", messages, visionImage),
  openSettingsWindow: () => electron.ipcRenderer.send("open-settings-window"),
  getConfig: () => electron.ipcRenderer.invoke("get-config"),
  saveConfig: (patch) => electron.ipcRenderer.invoke("save-config", patch),
  summarizeMemory: (evictedMessages) => electron.ipcRenderer.invoke("summarize-memory", evictedMessages),
  getMemoryList: () => electron.ipcRenderer.invoke("get-memory-list"),
  clearMemory: () => electron.ipcRenderer.invoke("clear-memory"),
  addMemory: (text) => electron.ipcRenderer.invoke("add-memory", text),
  deleteMemory: (id) => electron.ipcRenderer.invoke("delete-memory", id),
  proactiveChat: () => electron.ipcRenderer.invoke("proactive-chat"),
  ttsSynthesize: (text, emotion) => electron.ipcRenderer.invoke("tts-synthesize", text, emotion),
  sttTranscribe: (audioBuffer) => electron.ipcRenderer.invoke("stt-transcribe", audioBuffer),
  onToggleStt: (cb) => electron.ipcRenderer.on("toggle-stt", cb),
  onOpenChat: (cb) => electron.ipcRenderer.on("open-chat", cb),
  openUrl: (url) => electron.ipcRenderer.invoke("open-url", url),
  executeAction: (action) => electron.ipcRenderer.invoke("execute-action", action),
  onReminderFired: (cb) => electron.ipcRenderer.on("reminder-fired", (_, msg) => cb(msg)),
  saveCompressedInputs: (buffers) => electron.ipcRenderer.invoke("save-compressed-inputs", buffers),
  takeScreenshot: () => electron.ipcRenderer.invoke("take-screenshot"),
  getModels: () => electron.ipcRenderer.invoke("get-models"),
  onResetIdleTimer: (cb) => electron.ipcRenderer.on("reset-idle-timer", cb),
  onFocusEnd: (cb) => electron.ipcRenderer.on("focus-end", (_, msg) => cb(msg)),
  pickFolder: () => electron.ipcRenderer.invoke("pick-folder"),
  pickFile: (filters) => electron.ipcRenderer.invoke("pick-file", filters),
  loadToolAudio: (filename) => electron.ipcRenderer.invoke("load-tool-audio", filename),
  onGlobalCursor: (cb) => electron.ipcRenderer.on("global-cursor", (_, data) => cb(data)),
  executeCLI: (command, options) => electron.ipcRenderer.invoke("cli-execute", command, options),
  getCLIRegistry: () => electron.ipcRenderer.invoke("cli-get-registry"),
  getCLISystemPrompt: () => electron.ipcRenderer.invoke("cli-get-system-prompt")
});
